import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

/*
 * public/data/service-areas.json is the single source of truth for coverage,
 * but it lives under the publish directory: the browser can fetch it, and a
 * bundled Netlify Function cannot. Rather than keep a second hand-maintained
 * copy of the ZIP table beside the API -- which is exactly how a served ZIP
 * ends up rejected at submit time months after it was added -- this emits a
 * generated module from the same file, the way scripts/build-chat-knowledge.mjs
 * emits the chat corpus.
 *
 * The output is committed so `netlify dev` and a type check both work on a
 * clean checkout, and regenerated on every build so it cannot drift.
 */
const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const SOURCE = join(ROOT, 'public/data/service-areas.json');
const OUTPUT = join(ROOT, 'netlify/functions/generated/service-zones.mts');

const data = JSON.parse(readFileSync(SOURCE, 'utf8'));

const cities = Array.isArray(data.cities) ? data.cities : [];
if (cities.length === 0) {
  throw new Error(`No cities found in ${SOURCE}.`);
}

/*
 * A ZIP can legitimately span two of our cities -- 48323 and 48324 cover both
 * West Bloomfield and Orchard Lake, 48025 both Franklin and Beverly Hills --
 * so the first city listed wins and the rest are dropped. The zone and route
 * agree in every one of those pairs, which is what the API actually reads; the
 * city name is only ever a default the customer can correct in the form.
 */
const zipTable = {};
for (const city of cities) {
  for (const zip of city.zips || []) {
    if (zipTable[zip]) continue;
    zipTable[zip] = { city: city.name, slug: city.slug, zone: city.zone, route: city.route || null };
  }
}

const routes = data.routes && typeof data.routes === 'object' ? data.routes : {};

const banner = `// Generated by scripts/build-service-zones.mjs from public/data/service-areas.json.
// Do not edit manually -- edit the JSON and rebuild.
`;

const body = `${banner}
export type ServedZip = {
  city: string;
  slug: string;
  zone: string;
  route: string | null;
};

export type ServiceRoute = {
  label: string;
  days: number[];
  dayLabel: string;
  blurb: string;
};

export const SERVED_ZIPS: Record<string, ServedZip> = ${JSON.stringify(zipTable, null, 2)};

export const SERVICE_ROUTES: Record<string, ServiceRoute> = ${JSON.stringify(routes, null, 2)};
`;

mkdirSync(dirname(OUTPUT), { recursive: true });
writeFileSync(OUTPUT, body, 'utf8');

console.log(
  `Wrote netlify/functions/generated/service-zones.mts (${Object.keys(zipTable).length} ZIPs, ${Object.keys(routes).length} routes).`,
);
